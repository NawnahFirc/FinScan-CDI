function cleanCurrencyInput(value) {
  return String(value || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim()
}

function normalizeCurrencyWords(value) {
  return cleanCurrencyInput(value)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
}

export function isKnownCurrencyCode(code) {
  return Boolean(ISO_CURRENCIES[String(code || '').toUpperCase()])
}

export function normalizeCurrencyCode(value) {
  const raw = cleanCurrencyInput(value)
  if (!raw) return null
  const upper = raw.toUpperCase().replace(/[^A-Z]/g, '')
  if (isKnownCurrencyCode(upper)) {
    return { code: upper, confidence: 'high', source: raw }
  }
  return detectCurrencyFromText(raw)
}

export function detectCurrencyFromText(text = '') {
  const raw = String(text || '')
  if (!raw.trim()) return { code: null, confidence: 'none', source: 'not detected' }

  for (const rule of DETECTION_PATTERNS) {
    const matched = rule.patterns.find(pattern => pattern.test(raw))
    if (matched) {
      return {
        code: rule.code,
        confidence: rule.confidence,
        source: matched.source,
      }
    }
  }

  const explicitCode = raw.match(/\b(?:currency|devise|monnaie|moneda|amounts?\s+in|expressed\s+in|presented\s+in|thousands?\s+of|millions?\s+of|en\s+milliers\s+de|en\s+millions\s+de)\s*:?\s*([A-Z]{3})\b/i)?.[1]?.toUpperCase()
  if (explicitCode && isKnownCurrencyCode(explicitCode)) {
    return { code: explicitCode, confidence: 'high', source: explicitCode }
  }

  const trimmedCode = raw.trim().toUpperCase()
  if (/^[A-Z]{3}$/.test(trimmedCode) && isKnownCurrencyCode(trimmedCode)) {
    return { code: trimmedCode, confidence: 'high', source: trimmedCode }
  }

  const normalizedText = normalizeCurrencyWords(raw)
  for (const [code, label] of Object.entries(ISO_CURRENCIES)) {
    const normalizedName = normalizeCurrencyWords(label)
    const escapedName = normalizedName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    if (normalizedName && new RegExp(`(^|\\s)${escapedName}s?(\\s|$)`).test(normalizedText)) {
      return { code, confidence: 'high', source: label }
    }
  }

  if (/\$|¥|FCFA|\bCFA\b/i.test(raw)) {
    return {
      code: null,
      confidence: 'ambiguous',
      source: 'ambiguous currency symbol or label',
    }
  }

  return { code: null, confidence: 'none', source: 'not detected' }
}

export function getFxRateToEUR(currency) {
  const code = normalizeCurrencyCode(currency)?.code
  if (!code) return { rate: 1, known: false, code: UNKNOWN_CURRENCY }
  const quote = FX_QUOTES_PER_EUR[code]
  if (!quote) return { rate: 1, known: false, code }
  return { rate: 1 / quote, known: true, code }
}

export function currencyLabel(code) {
  const normalized = normalizeCurrencyCode(code)?.code || UNKNOWN_CURRENCY
  if (normalized === UNKNOWN_CURRENCY) return 'Unknown currency'
  return `${normalized} - ${ISO_CURRENCIES[normalized] || 'Currency'}`
}
